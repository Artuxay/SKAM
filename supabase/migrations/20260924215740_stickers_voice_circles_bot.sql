-- СКАМ — бот рассказывает про стикеры «Голубь свободы», голосовые и кружочки.
--
-- Клиент теперь умеет стикеры, голосовые и кружочки (схема для них — в media_stickers_usernames),
-- а @username обязателен. Подсказки бота приведены в соответствие с тем, что есть в приложении:
-- скрепки для файлов и сквозного шифрования в клиенте пока нет, поэтому бот о них не обещает.
-- Таблицы и колонки из e2e_attachments не трогаем — они пригодятся, когда появится клиент с шифрованием.

create or replace function private.bot_reply()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  t text := lower(btrim(new.body));
  nm text;
  reply text;
begin
  if not exists (select 1 from public.chats where id = new.chat_id and kind = 'bot') then
    return null;
  end if;
  select first_name into nm from public.profiles where id = new.user_id;

  if new.kind = 'sticker' then
    reply := 'Голубь Свободы одобряет 🕊️';
  elsif new.kind = 'voice' then
    reply := 'Голосовое получил! Но слушать я пока не умею — я же бот 🙈 Напишите текстом, отвечу.';
  elsif new.kind = 'video_note' then
    reply := 'Кружочек получил — выглядите свободно! 🕊️ Смотреть видео я пока не умею, но друзьям понравится.';
  elsif new.kind = 'media' then
    reply := 'Вложение получил 📎 Открыть его я не могу — я же бот. Друзьям лучше отправьте стикер, голосовое или кружочек.';
  elsif t ~ '^(/start|привет|прив|здравствуй|здрасте|здорово|добр(ый|ое|ого)|хай|хелло|салют|hi|hello|hey)' then
    reply := 'Привет, ' || coalesce(nm, 'друг') || '! 👋 Рад видеть. Напишите «помощь» — расскажу, что умею.';
  elsif t ~ '(помощь|помоги|help|команд|умеешь)' then
    reply := E'Я умею немного, но честно:\n• «привет» — поздороваюсь;\n• «помощь» — это сообщение;\n• «стикеры» — расскажу про Голубя свободы;\n• «это развод?» — объясню, почему нет.\n\nА ещё подскажу по СКАМ:\n• «Новый чат» — написать человеку по имени или @username или создать группу;\n• стикеры — кнопка со смайликом слева от поля ввода, а если набрать эмодзи, стикеры к нему появятся сами;\n• голосовое — удерживайте микрофон справа от поля ввода и отпустите, чтобы отправить; уведите палец влево — отмена, вверх — запись без рук;\n• кружочек — нажмите на микрофон коротко, он превратится в камеру, дальше так же: удерживайте и говорите;\n• реакции — наведите на сообщение или коснитесь его (на телефоне — долгое нажатие);\n• имя, @username, фото и тема — в профиле внизу слева.';
  elsif t ~ '(стикер|голуб|sticker)' then
    reply := E'🕊️ Голубь свободы — маскот СКАМ и наш официальный набор из 16 стикеров: «Привет!», «Да», «Нет», «Ха-ха-ха», «Люблю», «Что?!», «Жду», «Спокойной ночи», «Грусть», «Бесишь!», «Хм…», «Свобода!», «Не развод», «Спасибо», «Доброе утро» и «OK».\n\nНажмите на смайлик слева от поля ввода или просто наберите 👋, 😂 или 🤔 — подходящий голубь появится сам. Пришлите мне любой — оценю!';
  elsif t ~ '(голосов|кружоч|кружк|видеосообщ|микрофон|камер)' then
    reply := E'🎤 Голосовое: удерживайте микрофон справа от поля ввода, говорите и отпустите — сообщение уйдёт. Передумали — уведите палец влево. Долго говорить — потяните вверх, запись закрепится.\n\n⚪ Кружочек: коротко нажмите на микрофон — он станет камерой. Дальше так же: удерживайте, до минуты.\n\nСлушают и смотрят только участники чата.';
  elsif t ~ '(шифр|безопас|e2e|encrypt|ключ)' then
    reply := 'Сквозное шифрование в СКАМ пока в работе 🔧 Уже сейчас чужие чаты, голосовые и кружочки недоступны посторонним: доступ к каждому сообщению и файлу проверяет база, а файлы лежат в закрытом хранилище.';
  elsif t ~ '(развод|скам|мошен|scam|обман)' then
    reply := 'СКАМ — не развод, а мессенджер. Честно-честно 🤞 Чужие чаты никто не видит: доступ к каждому сообщению проверяет база.';
  elsif t ~ '(спасибо|спс|благодар)' then
    reply := 'Всегда пожалуйста! 🧡';
  elsif t ~ '(пока|до свидания|бывай)' then
    reply := 'До встречи! Я всегда здесь 👋';
  else
    reply := 'Я пока простой бот и понимаю немного 🙂 Напишите «помощь» — расскажу, что умею. А болтать веселее с людьми: создайте чат и позовите друзей.';
  end if;

  insert into public.messages (chat_id, user_id, kind, body, created_at)
  values (new.chat_id, null, 'system', reply, clock_timestamp());
  return null;
end;
$$;
revoke all on function private.bot_reply() from public, anon, authenticated;
