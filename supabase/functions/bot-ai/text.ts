const FILE_LABEL: Record<string, string> = { photo: 'фото', video: 'видео', file: 'файл' };

/** История чата с ботом → сообщения для модели. Подряд идущие реплики одной стороны склеиваются. */
export function toChat(history: Hist[], maxChars = 24000): ChatMsg[] {
  const out: ChatMsg[] = [];
  for (const h of history) {
    let text = (h.text ?? '').trim();
    if (h.role === 'user') {
      if (h.kind === 'sticker') text = `[стикер ${text}]`.replace(' ]', ']');
      else if (h.kind === 'voice') text = '[голосовое сообщение]';
      else if (h.kind === 'video_note') text = '[кружочек — видеосообщение]';
      else if (h.kind === 'poll') text = `[опрос: ${text}]`;
      else if (h.kind === 'media') {
        const kinds = [...new Set((h.files ?? []).map((k) => FILE_LABEL[k] ?? 'файл'))];
        text = `[${kinds.join(', ') || 'файл'}]${text ? ' ' + text : ''}`;
      }
    }
    if (!text) continue;
    const prev = out.at(-1);
    if (prev && prev.role === h.role) prev.content += '\n\n' + text;
    else out.push({ role: h.role, content: text });
  }
  // Модели нужен разговор, начатый человеком, и не слишком длинный.
  while (out.length && out[0].role !== 'user') out.shift();
  while (out.length && out.at(-1)!.role !== 'user') out.pop(); // модель не принимает разговор, кончающийся её репликой
  let total = out.reduce((n, m) => n + m.content.length, 0);
  while (out.length > 1 && total > maxChars) {
    total -= out.shift()!.content.length;
    while (out.length > 1 && out[0].role !== 'user') total -= out.shift()!.content.length;
  }
  const last = out.at(-1);
  if (last && last.content.length > maxChars) last.content = last.content.slice(-maxChars);
  return out;
}

/** Markdown → обычный текст для пузыря СКАМ (код не трогаем). */
export function plain(src: string): string {
  const code: string[] = [];
  const keep = (s: string) => `\u0000${code.push(s) - 1}\u0000`;
  let t = src.replace(/\r\n?/g, '\n');
  t = t.replace(/```[^\n`]*\n?([\s\S]*?)```/g, (_, c: string) => keep(c.replace(/\n+$/, '')));
  t = t.replace(/`([^`\n]+)`/g, (_, c: string) => keep(c));
  t = t.replace(/\[([^\]\n]+)\]\((https?:\/\/[^\s)]+)\)/g, (_, a: string, u: string) => (a.trim() === u ? u : `${a} (${u})`));
  t = t.replace(/^#{1,6}[ \t]+(.+?)[ \t]*#*[ \t]*$/gm, '$1');
  t = t.replace(/^[ \t]*([-*_])([ \t]*\1){2,}[ \t]*$/gm, '');
  t = t.replace(/^([ \t]*)[*+-][ \t]+/gm, '$1• ');
  t = t.replace(/\*\*([^\n]+?)\*\*/g, '$1').replace(/__([^\n]+?)__/g, '$1');
  t = t.replace(/(^|[\s(«"'])\*(?![\s*])([^*\n]+?)\*(?=[\s).,!?:;»"']|$)/gm, '$1$2');
  t = t.replace(/(^|[\s(«"'])_(?![\s_])([^_\n]+?)_(?=[\s).,!?:;»"']|$)/gm, '$1$2');
  t = t.replace(/^[ \t]*\|?[ \t]*:?-{3,}:?[ \t]*(\|[ \t]*:?-{3,}:?[ \t]*)*\|?[ \t]*$/gm, '');
  t = t.replace(/^[ \t]*\|(.+)\|[ \t]*$/gm, (_, row: string) => row.split('|').map((c) => c.trim()).filter(Boolean).join(' — '));
  t = t.replace(/[ \t]+$/gm, '').replace(/\n{3,}/g, '\n\n');
  t = t.replace(/\u0000(\d+)\u0000/g, (_, i: string) => code[Number(i)]);
  return t.trim();
}

/** Длинный ответ — на несколько сообщений (в базе до 4000 символов в сообщении). */
export function split(text: string, max = 3800, parts = 5): string[] {
  const out: string[] = [];
  let rest = text.trim();
  while (rest.length > max && out.length < parts - 1) {
    let cut = rest.lastIndexOf('\n\n', max);
    if (cut < max / 2) cut = rest.lastIndexOf('\n', max);
    if (cut < max / 2) cut = rest.lastIndexOf(' ', max);
    if (cut < max / 2) cut = max;
    out.push(rest.slice(0, cut).trim());
    rest = rest.slice(cut).trim();
  }
  if (rest.length > max) rest = rest.slice(0, max - 1).trimEnd() + '…';
  if (rest) out.push(rest);
  return out;
}

